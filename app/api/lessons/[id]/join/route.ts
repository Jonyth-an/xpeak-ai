import { NextRequest, NextResponse } from 'next/server';
import { RtcTokenBuilder, RtcRole } from 'agora-token';
import { serverSupabase } from '@/lib/serverSupabaseClient';

export async function POST(request: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id: lessonId } = await params;
    
    // Authenticate user
    const authHeader = request.headers.get('authorization');
    if (!authHeader?.startsWith('Bearer ')) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const token = authHeader.substring(7);
    const { data: { user }, error: authError } = await serverSupabase.auth.getUser(token);
    
    if (authError || !user) {
      return NextResponse.json({ error: 'Invalid token' }, { status: 401 });
    }

    // Get lesson details
    const { data: lesson, error: lessonError } = await serverSupabase
      .from('lessons')
      .select('*')
      .eq('id', lessonId)
      .single();

    if (lessonError || !lesson) {
      return NextResponse.json({ error: 'Lesson not found' }, { status: 404 });
    }

    // Check if user has access
    const { data: tutorProfile } = await serverSupabase
      .from('tutor_profiles')
      .select('id')
      .eq('user_id', user.id)
      .single();

    const isTutor = tutorProfile?.id === lesson.tutor_id;
    const isStudent = user.id === lesson.student_id;

    if (!isTutor && !isStudent) {
      return NextResponse.json({ error: 'Access denied' }, { status: 403 });
    }

    // Check if lesson is ready to start (allow 1 hour early for testing)
    const now = new Date();
    const lessonStart = new Date(lesson.scheduled_start);
    const lessonEnd = new Date(lesson.scheduled_end);
    const oneHourBefore = new Date(lessonStart.getTime() - 60 * 60 * 1000); // 1 hour before
    
    if (now < oneHourBefore) {
      return NextResponse.json({ 
        error: 'Lesson has not started yet',
        scheduledStart: lesson.scheduled_start 
      }, { status: 400 });
    }

    if (now > lessonEnd) {
      return NextResponse.json({ 
        error: 'Lesson has ended',
        scheduledEnd: lesson.scheduled_end 
      }, { status: 400 });
    }

    // Get the channel name from the request body (generated by frontend)
    let channelName;
    try {
      const body = await request.json();
      channelName = body?.channelName;
    } catch (error) {
      console.error('Error parsing request body:', error);
      return NextResponse.json({ error: 'Invalid request body' }, { status: 400 });
    }
    
    if (!channelName) {
      return NextResponse.json({ error: 'Channel name is required' }, { status: 400 });
    }

    // Generate Agora token
    const appID = process.env.AGORA_APP_ID!;
    const appCertificate = process.env.AGORA_APP_CERTIFICATE!;
    
    if (!appID || !appCertificate) {
      console.error('Missing Agora credentials:', { appID: !!appID, appCertificate: !!appCertificate });
      return NextResponse.json({ error: 'Video service configuration error' }, { status: 500 });
    }
    
    // Generate unique UID using a simple but effective approach
    const userHash = user.id.split('').reduce((a, b) => {
      a = ((a << 5) - a) + b.charCodeAt(0);
      return a & a;
    }, 0);
    
    const lessonHash = lessonId.split('').reduce((a, b) => {
      a = ((a << 5) - a) + b.charCodeAt(0);
      return a & a;
    }, 0);
    
    const timestamp = Date.now();
    const randomOffset = Math.floor(Math.random() * 1000000);
    
    // Combine factors for uniqueness
    const combinedHash = userHash + lessonHash + timestamp + randomOffset;
    const uid = Math.abs(combinedHash) % 1000000; // Use 1M range
    
    const role = RtcRole.PUBLISHER;
    const expirationTimeInSeconds = 3600; // 1 hour
    const currentTimestamp = Math.floor(Date.now() / 1000);
    const privilegeExpiredTs = currentTimestamp + expirationTimeInSeconds;

    console.log('🔑 Generating Agora token with:', {
      appID: appID.substring(0, 8) + '...',
      appCertificate: appCertificate.substring(0, 8) + '...',
      channelName,
      uid,
      role,
      privilegeExpiredTs
    });

    // Try different token generation methods
    let agoraToken;
    
    try {
      // Method 1: buildTokenWithUid (current method)
      agoraToken = RtcTokenBuilder.buildTokenWithUid(
        appID,
        appCertificate,
        channelName,
        uid,
        role,
        privilegeExpiredTs,
        privilegeExpiredTs
      );
      
      if (!agoraToken) {
        throw new Error('buildTokenWithUid returned null');
      }
      
      console.log('✅ Generated token using buildTokenWithUid');
    } catch (error) {
      console.error('❌ buildTokenWithUid failed:', error);
      
      try {
        // Method 2: buildTokenWithUserAccount (fallback)
        const account = uid.toString();
        agoraToken = RtcTokenBuilder.buildTokenWithUserAccount(
          appID,
          appCertificate,
          channelName,
          account,
          role,
          privilegeExpiredTs,
          privilegeExpiredTs
        );
        
        if (!agoraToken) {
          throw new Error('buildTokenWithAccount returned null');
        }
        
        console.log('✅ Generated token using buildTokenWithAccount');
      } catch (fallbackError) {
        console.error('❌ buildTokenWithAccount also failed:', fallbackError);
        return NextResponse.json({ error: 'Failed to generate video token' }, { status: 500 });
      }
    }

    console.log('✅ Generated token successfully');
    console.log('📋 Token details:', {
      tokenLength: agoraToken.length,
      tokenPreview: agoraToken.substring(0, 50) + '...',
      channelName,
      uid,
      appID: appID.substring(0, 8) + '...'
    });

    return NextResponse.json({
      lesson,
      channelName,
      token: agoraToken,
      uid,
      appID,
      role: role,
      userRole: isTutor ? 'tutor' : 'student',
      canJoin: true
    });

  } catch (error) {
    console.error('Error joining lesson:', error);
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
} 